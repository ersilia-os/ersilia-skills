"""The formal assessment: the same evidence as the report, written up as a procedure that
follows the official rules and guidance on AI use in research and on handling suspected
breaches (references/frameworks.json, references/formal-assessment.md).

There is no official EU guideline on detecting AI-written text, so this document claims
to be aligned with the sources it cites, step by step, never certified by them:

    1  the question and the rule that applies         (journal / funder / institution)
    2  confidentiality and what left the machine      (living guidelines, ERC, GDPR)
    3  two propositions, stated before the evidence   (ENFSI: balance)
    4  findings by line of evidence, each re-checkable, with its known error rate
                                                      (ENFSI: robustness, transparency)
    5  evaluation: strength of support, never the probability of guilt (ENFSI: logic)
    6  what the assessment does not show
    7  human review: no conclusion on automated output alone   (GDPR Art. 22)
    8  next steps: a neutral question; the competent body decides (COPE, ALLEA)
    9  the record: versions, dates, a hash of the text  (ENFSI: transparency)

It reads the work folder (after grade.py) and never the document's authors' names.
"""

from __future__ import annotations

import hashlib
import html
import math
import subprocess
from pathlib import Path

from lib.common import ASSETS, REFS, SKILL_DIR, read_json
from lib.report import BAD_REF, CONTEXT, TIER_WORD

PROPOSITIONS = (
    "A substantial part of the text was generated by a generative-AI tool, and this was not disclosed.",
    (
        "The text was written by its author(s), possibly with AI help limited to language polishing, "
        "which the applicable guidance does not require to be disclosed."
    ),
)

# ENFSI Guideline for Evaluative Reporting (2015), example verbal scale for a likelihood ratio.
VERBAL = (
    (2, "no support for either proposition over the other"),
    (10, "weak support"),
    (100, "moderate support"),
    (1000, "moderately strong support"),
    (10000, "strong support"),
    (1000000, "very strong support"),
    (math.inf, "extremely strong support"),
)
# The detectors' likelihood ratios come from small test sets (tens of texts), so the
# statistical line is never worded above this level, whatever the number.
VERBAL_CAP = "moderate support"

NEXT_STEPS = {
    "collaborator-draft": (
        (
            "Ask the collaborator directly, in a neutral tone, how the text was prepared and which tools were used; "
            "share this document. As a co-author you are responsible for the content too, so agree what must be "
            "checked, rewritten or disclosed before submission."
        ),
        ["cope-case", "living-guidelines", "allea"],
    ),
    "reviewer-of-my-paper": (
        (
            "Write to the handling editor, not to the reviewer. Lead with what the editor can verify (claims about "
            "the manuscript that are false, requests for analyses it already contains), attach this document, and "
            "ask the editor to consider the review's reliability. The editor decides."
        ),
        ["cope-case", "cope-forum", "allea", "living-guidelines"],
    ),
    "manuscript-i-review": (
        (
            "Report the concern to the handling editor in the confidential comments of your review, with the "
            "verifiable findings. Do not contact the authors, and do not send the manuscript to any online tool. "
            "The journal decides and, by COPE advice, starts with a neutral question to the authors."
        ),
        ["cope-case", "icmje", "living-guidelines"],
    ),
    "grant-i-review": (
        (
            "Report the concern to the programme officer or call coordinator, confidentially, with the verifiable "
            "findings (references that do not exist, false claims). Do not lower a score because AI may have been "
            "used: assess what is written. The funder decides."
        ),
        ["he-briefing", "erc-evaluation", "living-guidelines"],
    ),
    "other": (
        (
            "Ask the author, in a neutral tone, how the text was prepared, and share this document. Any decision "
            "belongs to whoever is responsible for the rule that applies."
        ),
        ["cope-case", "allea"],
    ),
}


def e(x: object) -> str:
    """HTML-escape."""
    return html.escape("" if x is None else str(x))


def verbal(lr: float) -> str:
    """ENFSI-style words for a likelihood ratio (either direction), capped."""
    x = max(lr, 1 / lr) if lr > 0 else math.inf
    words = next(w for bound, w in VERBAL if x < bound)
    order = [w for _, w in VERBAL]
    if order.index(words) > order.index(VERBAL_CAP):
        words = VERBAL_CAP
    if words.startswith("no support"):
        return words
    return f"{words} for proposition {'1' if lr >= 1 else '2'}"


def tool_version() -> str:
    """The skill's git commit, for the record."""
    try:
        out = subprocess.run(
            ["git", "-C", str(SKILL_DIR), "log", "-1", "--format=%h (%cs)"],
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        return out.stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def _cite(sources: dict, ids: list[str]) -> str:
    """'Basis: ...' line naming the sources (Annex A has the words)."""
    names = [
        f"{sources[i]['title']} ({sources[i]['status']})" for i in ids if i in sources
    ]
    return (
        f'<p class="basis">Basis: {e("; ".join(names))}. See Annex A.</p>'
        if names
        else ""
    )


def _row(line: str, finding: str, recheck: str, limits: str, support: str) -> str:
    return (
        f"<tr><th>{e(line)}</th><td>{finding}</td><td>{recheck}</td>"
        f"<td>{limits}</td><td>{support}</td></tr>"
    )


def findings_table(work: Path, grade: dict) -> str:
    """One row per line of evidence, run or not, with how to re-check it and its limits."""
    arts = read_json(work / "artifacts.json") or {"hits": [], "hidden": []}
    refs = (read_json(work / "references.json") or {}).get("references", [])
    jud = read_json(work / "judgements.json") or {}
    sty = (read_json(work / "stylometry.json") or {}).get("summary") or {}
    evd = read_json(work / "evidence.json") or {}
    web = read_json(work / "web_detectors.json") or {}
    cal = (read_json(REFS / "calibration.json") or {}).get("stylometry") or {}
    rules = read_json(REFS / "grading.json") or {}
    ja, jr = jud.get("artifacts", {}), jud.get("references", {})
    leftover_cats = set(rules.get("conclusive", {}).get("categories", [])) | set(
        rules.get("strong", {}).get("strong_categories", [])
    )
    rows = []

    hits = [
        h
        for h in arts["hits"]
        if ja.get(h["id"], {}).get("confirmed", True)
        and h["category"] in leftover_cats
        and h["tier"] in ("conclusive", "strong")
    ]
    rows.append(
        _row(
            "Leftover output of an AI tool",
            (
                f"{len(hits)} found: "
                + "; ".join(
                    f"“{e(h['match'][:80])}” ({e(h.get('section') or h['in'])})"
                    for h in hits[:5]
                )
                if hits
                else "None found."
            ),
            "Search the document for the quoted strings.",
            "Strings no person types by hand; each was read in context to rule out quotation.",
            "Direct observation; supports proposition 1" if hits else "None",
        )
    )
    separate = grade.get("separate", [])
    rows.append(
        _row(
            "Hidden text, instructions to AI tools, paraphrasing software",
            "<br>".join(e(s["text"]) for s in separate) if separate else "None found.",
            "Select all text in the file, or extract it; compare with the visible page.",
            "Reported apart: serious, but not evidence of who wrote the text.",
            "Separate matter" if separate else "None",
        )
    )
    bad = [
        r
        for r in refs
        if r["status"] in BAD_REF and jr.get(str(r["n"]), {}).get("fabricated", True)
    ]
    rows.append(
        _row(
            "References",
            (
                f"{len(bad)} of {len(refs)} could not be found as cited: "
                + "; ".join(
                    f"no. {r['n']} ({e(BAD_REF[r['status']])})" for r in bad[:6]
                )
                if bad
                else (
                    f"All {len(refs)} checked; none missing."
                    if refs
                    else "No reference list found."
                )
            ),
            "Look each one up in Crossref, DataCite, doi.org, OpenAlex, arXiv or Semantic Scholar; the lookups used are kept with the case.",
            "A real paper cited with wrong details is a human error too; only references not found anywhere, "
            "confirmed by a manual search, count.",
            "Verifiable fact; supports proposition 1" if bad else "None",
        )
    )
    reading = jud.get("reading", [])
    limits = (
        "A quoted, checkable observation; graded weak unless it is a verified false claim "
        "or invented fact."
    )
    for k, r in enumerate(reading, 1):  # one row per note
        rows.append(
            _row(
                f"Close reading, note {k}",
                f"{e(r['claim'])} <i>“{e(r.get('quote', ''))}”</i> ({e(r.get('where', ''))})",
                e(r.get("check", "")) or "Read the quoted passage.",
                limits,
                e(r.get("tier", "weak").capitalize()),
            )
        )
    if not reading:
        rows.append(_row("Close reading", "Nothing to note.", "—", limits, "None"))
    doc = evd.get("document") or {}
    if doc.get("evidence") is not None:
        lr = math.exp(doc["evidence"])
        top = max(
            (p for p in evd.get("passages", []) if p.get("evidence") is not None),
            key=lambda p: p["evidence"],
            default=None,
        )
        tools = evd.get("tools", {})
        cals = {t: (tools.get(t) or {}).get("cal") or {} for t in evd.get("used", [])}
        record = (
            "; ".join(
                f"{t}: {round((c.get('fpr') or 0) * c['n_human'])}/{c['n_human']} false alarms, "
                f"{round((c.get('tpr') or 0) * c['n_ai'])}/{c['n_ai']} AI texts caught"
                for t, c in cals.items()
                if c.get("n_human") and c.get("n_ai")
            )
            or "see web_validation.md"
        )
        rows.append(
            _row(
                "AI-text detectors (statistical)",
                f"{len(evd.get('used', []))} detectors, each first tested on texts of known origin, run on several "
                f"splits of the prose. Whole text: the results are about {lr:.1f} times as likely under proposition 1 "
                f"as under proposition 2"
                + (
                    f"; most AI-like passage ({e(top['chunk'])}): about {math.exp(top['evidence']):.1f} times."
                    if top
                    else "."
                ),
                "Paste the same passages into the same sites; the passages and every result page are kept with the case.",
                f"Records on known texts: {e(record)}. Small test sets; detectors err more on non-native English and "
                "on professionally edited text, and miss AI text that imitates an author's style.",
                e(verbal(lr)),
            )
        )
    else:
        skipped = "; ".join(
            f"{s['tool']}: {s['why']}" for s in web.get("skipped", [])[:3]
        )
        rows.append(
            _row(
                "AI-text detectors (statistical)",
                "Not run."
                + (
                    f" {e(skipped)}"
                    if skipped
                    else " The text is confidential, or they were not run this time."
                ),
                "—",
                "Unpublished manuscripts, proposals and reviews are not sent to online tools.",
                "None",
            )
        )
    wo = (sty.get("windows_over") or {}).get("1%")
    held = (cal.get("heldout") or {}).get("human (held out)") or {}
    nn = (cal.get("heldout") or {}).get("human, non-English-speaking country") or {}
    rows.append(
        _row(
            "Style (vocabulary, stock phrasing, sentence rhythm)",
            f"{wo['count']} of {sty.get('n_windows')} windows past the threshold."
            if wo
            else "Not scored (text too short).",
            "The word lists are published (Kobak et al. 2025; Liang et al. 2024).",
            f"On held-out human scientific text the threshold flags {100 * held.get('past_1pct', 0):.1f}% of windows "
            f"({100 * nn.get('past_1pct', 0):.1f}% for authors in non-English-speaking countries). "
            "It does not detect recent Claude text. Context only.",
            "Weak at most",
        )
    )
    wm = jud.get("watermark") or []
    rows.append(
        _row(
            "Provider watermark (Claude, ChatGPT)",
            "<br>".join(
                f"{e(w.get('provider'))}: {e(w.get('result'))} ({e(w.get('date', ''))})"
                for w in wm
            )
            if wm
            else "Not checked: verification is open only to approved organisations and researchers.",
            "Request access from the provider (see watermarks.md).",
            "A detected mark shows the text was processed by that model, including for translation or proofreading; "
            "a missing mark shows nothing.",
            "See result" if wm else "None",
        )
    )
    return (
        '<div class="scroll"><table class="findings"><thead><tr><th>Line of evidence</th><th>Finding</th>'
        "<th>How anyone can re-check it</th><th>Known error rate and limits</th><th>Support</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div>"
    )


def annex_sources(fw: dict, kind: str) -> str:
    """Annex A: every source, its status, the words relied on, and how they were checked."""
    out = []
    for s in fw["sources"]:
        if s.get("applies") and kind not in s["applies"]:
            continue
        quotes = "".join(
            f"<li><b>{e(p['ref'])}:</b> “{e(p['quote'])}” <span class='use'>{e(p['use'])}</span></li>"
            for p in s["provisions"]
        )
        note = f'<p class="note">{e(s["note"])}</p>' if s.get("note") else ""
        out.append(
            f'<section class="src"><h4>{e(s["title"])}</h4>'
            f'<p class="meta">{e(s["body"])} · {e(s["date"])} · <b>{e(s["status"])}</b> · '
            f'<a href="{e(s["url"])}">source</a><br>Checked {e(s["checked"])}</p><ul>{quotes}</ul>{note}</section>'
        )
    return "".join(out)


def render(
    work: Path,
    case: str,
    kind: str,
    context: str,
    date: str,
    assessor: str = "",
    policy: str = "",
) -> str:
    """The formal assessment as an HTML fragment."""
    grade = read_json(work / "grade.json") or {}
    doc = read_json(work / "text.json") or {}
    web = read_json(work / "web_detectors.json") or {}
    fw = read_json(REFS / "frameworks.json")
    sources = {s["id"]: s for s in fw["sources"]}
    policies = [
        p
        for p in (read_json(REFS / "policies.json") or {}).get("policies", [])
        if kind in p.get("applies", [])
    ]
    digest = hashlib.sha256(doc.get("text", "").encode("utf-8")).hexdigest()
    names = {
        t["id"]: t["name"]
        for t in (read_json(REFS / "web_detectors.json") or {}).get("tools", [])
    }
    services = sorted({names.get(r["tool"], r["tool"]) for r in web.get("results", [])})
    confidential = context in ("manuscript-i-review", "grant-i-review")
    tier = grade.get("tier", "none")
    step, basis = NEXT_STEPS.get(context, NEXT_STEPS["other"])
    versions = {
        "Tool version": tool_version(),
        "Grading rules": f"v{(read_json(REFS / 'grading.json') or {}).get('version')}",
        "Artefact patterns": f"v{(read_json(REFS / 'markers.json') or {}).get('version')}",
        "Detector registry": f"v{(read_json(REFS / 'web_detectors.json') or {}).get('version')}",
        "Sources reviewed": fw.get("reviewed"),
        "Text assessed": f"{doc.get('n_words')} words; SHA-256 {digest[:16]}…{digest[-8:]}",
        "Detector runs": ", ".join(
            sorted({r.get("date", "") for r in web.get("results", [])})
        )
        or "none",
    }
    css = (ASSETS / "formal.css").read_text(encoding="utf-8")
    return (
        f"<title>{e(case[:50])}</title>\n<style>{css}</style>\n<main>"
        '<p class="kicker">Assessment of possible undisclosed use of generative AI</p>'
        f"<h1>{e(case)}</h1>"
        f'<p class="meta">{e(kind.replace("-", " ").capitalize())} · {e(CONTEXT.get(context, context))} · '
        f"assessed {e(date)}{' by ' + e(assessor) if assessor else ''}</p>"
        '<div class="box"><p><b>What this document is.</b> A record of evidence, gathered by a fixed procedure, on '
        "whether a text was written with generative AI without disclosure. Each step follows a cited rule or "
        "guidance document (Annex A), and every finding can be re-checked by someone else.</p>"
        "<p><b>What it is not.</b> It is not proof of authorship, not a finding of misconduct, and not legal advice. "
        "No official EU guideline exists for detecting AI-written text, and no detector is approved as evidence: "
        "this assessment is aligned with the rules it cites, not certified by them. Using AI is not in itself a "
        "breach; hiding substantial use is what the integrity codes name.</p></div>"
        "<h2>1. The question and the rule that applies</h2>"
        "<p>Whether the text shows evidence of substantial generative-AI use that was not disclosed. What must be "
        "disclosed is set by the journal, funder or institution concerned; EU-level guidance asks researchers to "
        "disclose substantial use and treats language polishing as not substantial.</p>"
        + (
            f"<p><b>Rule named for this case:</b> {e(policy)}</p>"
            if policy
            else "<p><b>Rule named for this case:</b> none given. Before raising the matter, check the disclosure rule of "
            "the journal, funder or institution concerned; it takes precedence over general guidance.</p>"
        )
        + _cite(
            sources,
            ["living-guidelines", "allea"] + (["he-form"] if kind == "grant" else []),
        )
        + "<h2>2. Confidentiality</h2>"
        + (
            "<p>This text is under confidential review. It was analysed on the assessor's machine only and was "
            "not sent to any AI detector or other online service; only reference details (titles, DOIs) were "
            "looked up in public bibliographic databases.</p>"
            if confidential or not services
            else f"<p>Passages of the text were sent to these detector services, which the assessor approved for "
            f"this text: {e(', '.join(services))}. No confidential manuscript, proposal or review was sent. "
            "Reference details were looked up in public bibliographic databases.</p>"
        )
        + "<p>The case is identified by a neutral label; this document names no person.</p>"
        + _cite(sources, ["living-guidelines", "erc-evaluation", "allea", "gdpr"])
        + "<h2>3. The two propositions</h2>"
        "<p>The evidence is weighed under two propositions, stated before looking at it:</p>"
        f"<ol class='props'><li>{e(PROPOSITIONS[0])}</li><li>{e(PROPOSITIONS[1])}</li></ol>"
        + _cite(sources, ["enfsi"])
        + "<h2>4. Findings</h2>"
        + findings_table(work, grade)
        + _cite(sources, ["enfsi"])
        + "<h2>5. Evaluation</h2>"
        f'<p class="verdict"><b>{e(TIER_WORD.get(tier, tier))}.</b> '
        f"{e(grade.get('headline', '').split(': ', 1)[-1].capitalize())}</p>"
        "<p>The grade is the highest of five levels whose rule is met: conclusive (leftover AI-tool output), strong "
        "(verifiable problems such as fabricated references), moderate (one independent line), weak (context only), "
        "none. Statistical lines alone never go above moderate. The statements below are worded as support for a "
        "proposition; none states the probability that the author used AI.</p><ul>"
        + "".join(
            f"<li><b>{e(s['tier'].capitalize())}:</b> {e(s['text'])}"
            + (
                f" <span class='use'>Re-check: {e(s['check'])}</span>"
                if s.get("check")
                else ""
            )
            + "</li>"
            for s in grade.get("statements", [])
        )
        + (
            ""
            if grade.get("statements")
            else "<li>No finding supports proposition 1.</li>"
        )
        + "</ul>"
        + _cite(sources, ["enfsi"])
        + "<h2>6. What this assessment does not show</h2><ul>"
        + "".join(f"<li>{e(c)}</li>" for c in grade.get("caveats", []))
        + "<li>It does not identify which tool, if any, was used, or who used it.</li>"
        "<li>It does not show intent: non-disclosure can be an oversight.</li></ul>"
        + _cite(sources, ["oia-note", "turnitin", "cope-forum"])
        + "<h2>7. Human review</h2>"
        "<p>The automated checks produce evidence; they decide nothing. The assessor read the findings in context, "
        "set aside false alarms, verified suspect references by hand, and is responsible for this document. No "
        "conclusion here rests on a detector score alone.</p>"
        f'<p class="sign">Reviewed by: {e(assessor) if assessor else "________________________"} '
        f"&nbsp; Date: {e(date)} &nbsp; Signature: ________________________</p>"
        + _cite(sources, ["gdpr", "cope-forum"])
        + "<h2>8. Next steps</h2>"
        f"<p>{e(step)}</p>"
        "<p>The person concerned should receive the full evidence and be able to respond before anyone concludes "
        "anything; they are presumed to have acted properly until the competent body finds otherwise; any "
        "consequence must be proportionate; and if the concern does not hold, it should be withdrawn explicitly. "
        "An unfounded accusation is itself a breach of research integrity.</p>"
        + _cite(sources, [*basis, "allea"])
        + "<h2>9. Record</h2><table class='record'>"
        + "".join(
            f"<tr><th>{e(k)}</th><td>{e(v)}</td></tr>" for k, v in versions.items()
        )
        + "</table><p>The detectors' results on texts of known origin, and the style score's error rates, are "
        "published with the tool (web_validation.md, validation.md). Result pages, screenshots and reference "
        "lookups are kept with the case.</p>"
        + _cite(sources, ["enfsi"])
        + '<h2 class="annex">Annex A. Sources, their status, and the words relied on</h2>'
        + annex_sources(fw, kind)
        + (
            '<h2 class="annex">Annex B. Policies that may apply</h2><p class="note">Summaries only; policies '
            "change, so read the current text before quoting one.</p><ul>"
            + "".join(
                f'<li><b>{e(p["body"])}:</b> {e(p["summary"])} <a href="{e(p["url"])}">source</a></li>'
                for p in policies
            )
            + "</ul>"
            if policies
            else ""
        )
        + "</main>"
    )
